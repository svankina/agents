#!/usr/bin/env python3
"""agents-sync: generate per-agent global instruction files and skill symlinks
from the single source of truth in ~/src/agents.

Each target is composed as: banner + shared/AGENTS.md + <agent>/local.md,
with foreign managed blocks (<!-- name:begin --> ... <!-- name:end -->) found
in the existing target preserved at the end. See
docs/superpowers/specs/2026-07-03-agent-unification-design.md.
"""

import os
import re
from dataclasses import dataclass
from pathlib import Path

AGENTS = ["claude", "codex", "pi", "omp"]

BANNER_PREFIX = "<!-- GENERATED by agents-sync"

FOREIGN_BLOCK_RE = re.compile(
    r"<!--\s*([A-Za-z0-9_-]+):begin\b[^>]*-->\n?.*?<!--\s*\1:end\s*-->\n?",
    re.DOTALL,
)


@dataclass
class Target:
    agent: str
    path: Path
    local_md: Path


@dataclass
class Config:
    repo: Path
    home: Path

    @property
    def shared_md(self) -> Path:
        return self.repo / "shared" / "AGENTS.md"

    @property
    def shared_skills(self) -> Path:
        return self.repo / "shared" / "skills"

    def targets(self) -> list[Target]:
        paths = {
            "claude": self.home / ".claude" / "CLAUDE.md",
            "codex": self.home / ".codex" / "AGENTS.md",
            "pi": self.home / ".config" / "pi" / "AGENTS.md",
            "omp": self.home / ".omp" / "agent" / "AGENTS.md",
        }
        return [Target(a, paths[a], self.repo / a / "local.md") for a in AGENTS]

    def skill_dests(self) -> list[Path]:
        return [
            self.home / ".claude" / "skills",
            self.home / ".codex" / "skills",
            self.home / ".omp" / "agent" / "skills",
            self.repo / "pi" / "skills",
        ]

    def home_links(self) -> list[tuple[Path, Path]]:
        return [
            (self.home / "AGENTS.md", self.repo / "home" / "AGENTS.md"),
            (self.home / "CLAUDE.md", Path("AGENTS.md")),  # relative link
        ]


def banner(agent: str) -> str:
    return (
        f"<!-- GENERATED by agents-sync — do not edit here. Source: "
        f"~/src/agents/shared/AGENTS.md + ~/src/agents/{agent}/local.md. "
        f"Edit those, then run agents-sync. -->\n"
    )


def extract_foreign_blocks(text: str) -> list[str]:
    return [m.group(0).rstrip("\n") + "\n" for m in FOREIGN_BLOCK_RE.finditer(text)]


def compose(agent: str, shared_text: str, local_text: str,
            foreign_blocks: list[str]) -> str:
    parts = [banner(agent), "\n", shared_text.rstrip("\n") + "\n"]
    if local_text.strip():
        parts += ["\n", local_text.rstrip("\n") + "\n"]
    for block in foreign_blocks:
        parts += ["\n", block]
    return "".join(parts)


def expected_content(cfg: Config, t: Target) -> str:
    shared = cfg.shared_md.read_text()
    local = t.local_md.read_text() if t.local_md.exists() else ""
    current = t.path.read_text() if t.path.exists() else ""
    return compose(t.agent, shared, local, extract_foreign_blocks(current))


def target_state(t: Target, expected: str) -> str:
    if not t.path.exists():
        return "missing"
    current = t.path.read_text()
    if current == expected:
        return "clean"
    if current.startswith(BANNER_PREFIX):
        return "drifted"
    return "foreign"


def desired_skill_links(cfg: Config) -> list[tuple[Path, Path]]:
    links = []
    if cfg.shared_skills.is_dir():
        for skill in sorted(p for p in cfg.shared_skills.iterdir() if p.is_dir()):
            for dest in cfg.skill_dests():
                links.append((dest / skill.name, skill))
    return links


def link_state(link: Path, target: Path, repo: Path) -> str:
    if not link.is_symlink():
        if link.exists():
            return "conflict"
        return "missing"
    raw = os.readlink(link)
    try:
        resolved = link.resolve(strict=True)
    except OSError:
        resolved = None
    want = target if target.is_absolute() else (link.parent / target)
    if resolved is not None and resolved == want.resolve():
        return "clean"
    if raw.startswith(str(repo)):
        return "stale"
    return "conflict"


def apply_link(link: Path, target: Path) -> None:
    link.parent.mkdir(parents=True, exist_ok=True)
    if link.is_symlink():
        link.unlink()
    os.symlink(target, link)


def stale_repo_links(cfg: Config) -> list[Path]:
    valid = {link for link, _ in desired_skill_links(cfg)}
    out = []
    for dest in cfg.skill_dests():
        if not dest.is_dir():
            continue
        for entry in sorted(dest.iterdir()):
            if entry in valid or not entry.is_symlink():
                continue
            raw = os.readlink(entry)
            if raw.startswith(str(cfg.shared_skills)) and not entry.exists():
                out.append(entry)
    return out


if __name__ == "__main__":
    raise SystemExit(0)
